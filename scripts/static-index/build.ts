import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";
import { SITE_MEDIA } from "../../src/lib/site-media";
import { staticHref } from "./hrefs";

// Builds a self-contained index.html of the landing page from the Next.js build:
// the prerendered markup with CSS and fonts inlined, plus the real React
// components bundled so the page stays interactive when opened as a file.
const root = process.cwd();
const nextDir = path.join(root, ".next");
const prerendered = path.join(nextDir, "server/app/index.html");
const workspaceUrl = process.env.WORKSPACE_URL || "http://127.0.0.1:3215/create";
const output = path.join(root, "index.html");

const MIME: Record<string, string> = {
  ".woff2": "font/woff2",
  ".woff": "font/woff",
  ".png": "image/png",
  ".svg": "image/svg+xml",
};

/** Media lives in public/, which sits next to index.html at the repository root. */
function mediaPath(value: string) {
  return value.replace(/^\//, "public/");
}

function inlineStylesheet(href: string) {
  const file = path.join(nextDir, href.replace(/^\/_next\//, ""));
  return readFileSync(file, "utf8").replace(/url\(([^)]+)\)/g, (match, raw: string) => {
    const target = raw.trim().replace(/^["']|["']$/g, "");
    if (target.startsWith("data:") || target.startsWith("#")) return match;
    const asset = target.startsWith("/_next/")
      ? path.join(nextDir, target.slice("/_next/".length))
      : path.resolve(path.dirname(file), target);
    const mime = MIME[path.extname(asset)];
    if (!mime) throw new Error(`No MIME type for stylesheet asset ${target}.`);
    return `url(data:${mime};base64,${readFileSync(asset).toString("base64")})`;
  });
}

async function bundleLanding() {
  const result = await build({
    entryPoints: [path.join(root, "scripts/static-index/entry.tsx")],
    absWorkingDir: root,
    bundle: true,
    write: false,
    minify: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    jsx: "automatic",
    logLevel: "warning",
    define: {
      "process.env.NODE_ENV": '"production"',
      WORKSPACE_URL: JSON.stringify(workspaceUrl),
    },
    // Styles come from the Next.js build, which has already run Tailwind.
    loader: { ".css": "empty" },
    plugins: [
      {
        name: "static-index",
        setup(context) {
          context.onResolve({ filter: /^next\/link$/ }, () => ({
            path: path.join(root, "scripts/static-index/link.tsx"),
          }));
          context.onResolve({ filter: /^@\/lib\/site-media$/ }, () => ({
            path: "site-media",
            namespace: "static-index",
          }));
          context.onLoad({ filter: /.*/, namespace: "static-index" }, () => ({
            contents: `export const SITE_MEDIA = ${JSON.stringify(
              Object.fromEntries(Object.entries(SITE_MEDIA).map(([key, value]) => [key, mediaPath(value)])),
            )};`,
            loader: "js",
          }));
        },
      },
    ],
  });
  const code = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  if (code.includes("<!--"))
    throw new Error("The bundle contains <!--, which breaks parsing inside an inline <script>.");
  return code;
}

async function main() {
  if (!existsSync(prerendered))
    throw new Error("Missing .next/server/app/index.html. Run `next build` first.");

  const styles: string[] = [];
  let html = readFileSync(prerendered, "utf8")
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, "")
    .replace(/<link\b[^>]*>/g, (tag) => {
      const href = tag.match(/href="([^"]+)"/)?.[1];
      if (tag.includes('rel="stylesheet"') && href?.startsWith("/_next/")) {
        styles.push(inlineStylesheet(href));
        return "";
      }
      return /rel="(preload|modulepreload|icon)"/.test(tag) ? "" : tag;
    })
    .replace(/<meta name="next-size-adjust"[^>]*>/, "")
    .replace(/(href|src|poster)="(\/[^"]*)"/g, (_match, attribute: string, value: string) =>
      `${attribute}="${attribute === "href" ? staticHref(value, workspaceUrl) : mediaPath(value)}"`,
    )
    .replace(/url\((\/media\/[^)]*)\)/g, (_match, value: string) => `url(${mediaPath(value)})`);
  if (!styles.length) throw new Error("No stylesheets found in the prerendered page.");

  const script = await bundleLanding();
  html = html
    .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by `npm run build:html` from src/app/page.tsx. Edit the source, not this file. -->\n")
    .replace("</head>", `<style>${styles.join("\n")}</style></head>`)
    .replace(/<body([^>]*)>([\s\S]*)<\/body>/, (_match, attributes: string, body: string) =>
      `<body${attributes}><div id="root">${body}</div><script>${script}</script></body>`,
    );
  if (html.includes('"/_next/')) throw new Error("index.html still references /_next/ assets.");

  writeFileSync(output, html);
  console.log(`Wrote ${path.relative(root, output)} (${Math.round(html.length / 1024)} KB). Workspace links point to ${workspaceUrl}.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
